import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

function yamlQuote(value: string): string {
  const escaped = value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ");
  return `"${escaped}"`;
}

export function renderSkillMarkdown(
  slug: string,
  frontmatter: Record<string, string>,
  body: string,
  sourceUrl: string,
): string {
  return (
    `---\nname: ${slug}\ndescription: ${yamlQuote(frontmatter.description!)}\n---\n\n` +
    `${body}\n\n---\n*Generated by vid2skill from: ${sourceUrl}*\n`
  );
}

export function renderSummaryMarkdown(body: string, sourceUrl: string): string {
  return `${body}\n\n---\n*Generated by vid2skill from: ${sourceUrl}*\n`;
}

/** CLI-only: persist generated output to disk. The web app uses the render*
 * functions directly and returns the string in the API response instead. */
export async function writeSkill(
  outputDir: string,
  slug: string,
  frontmatter: Record<string, string>,
  body: string,
  sourceUrl: string,
): Promise<string> {
  const skillDir = path.join(outputDir, slug);
  await mkdir(skillDir, { recursive: true });
  const filePath = path.join(skillDir, "SKILL.md");
  await writeFile(filePath, renderSkillMarkdown(slug, frontmatter, body, sourceUrl), "utf-8");
  return filePath;
}

export async function writeSummary(
  outputDir: string,
  slug: string,
  body: string,
  sourceUrl: string,
): Promise<string> {
  await mkdir(outputDir, { recursive: true });
  const filePath = path.join(outputDir, `${slug}.md`);
  await writeFile(filePath, renderSummaryMarkdown(body, sourceUrl), "utf-8");
  return filePath;
}
