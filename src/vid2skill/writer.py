from pathlib import Path


def _yaml_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    return f'"{escaped}"'


def write_skill(output_dir: Path, slug: str, frontmatter: dict, body: str, source_url: str) -> Path:
    skill_dir = output_dir / slug
    skill_dir.mkdir(parents=True, exist_ok=True)

    content = (
        f"---\nname: {slug}\ndescription: {_yaml_quote(frontmatter['description'])}\n---\n\n"
        f"{body}\n\n---\n*Generated by vid2skill from: {source_url}*\n"
    )

    path = skill_dir / "SKILL.md"
    path.write_text(content, encoding="utf-8")
    return path


def write_summary(output_dir: Path, slug: str, body: str, source_url: str) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    content = f"{body}\n\n---\n*Generated by vid2skill from: {source_url}*\n"
    path = output_dir / f"{slug}.md"
    path.write_text(content, encoding="utf-8")
    return path
